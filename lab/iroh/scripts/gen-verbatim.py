def dedent(b):
    lines = b.splitlines()
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    return "\n".join(l[pad:] for l in lines)


def split_uses(b):
    uses, rest = [], []
    for l in dedent(b).splitlines():
        (uses if l.startswith("use ") else rest).append(l)
    return "\n".join(uses), "\n".join(rest)


def ind(s, n):
    return "\n".join((" " * n + l) if l.strip() else l for l in s.splitlines())


